export function detectLanguage(languages: readonly string[] = navigator.languages ?? []): Language {
  for (const tag of languages) {
    const base = tag.toLowerCase().split('-')[0];
    if (base === 'it') return 'it';
    if (base === 'en') return 'en';
  }
  return 'it';
}

export const language: Language =
  typeof navigator === 'undefined'
    ? 'it'
    : detectLanguage(navigator.languages ?? [navigator.language]);

const dictionaries: Record<Language, Record<MessageKey, string>> = { it, en };

export function t(key: MessageKey, vars: Record<string, string | number> = {}, lang = language) {
  return dictionaries[lang][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(vars[name] ?? ''),
  );
}

export const locale = language === 'it' ? 'it-IT' : 'en-GB';

/** Store and site pages in the reader's language. */
export function cleitextPage(slug: 'privacy-app' | 'supporto-app' | 'elimina-account-app') {
  if (language === 'it') return `https://cleitext.com/it/${slug}`;
  const english = {
    'privacy-app': 'privacy-app',
    'supporto-app': 'app-support',
    'elimina-account-app': 'delete-app-account',
  };
  return `https://cleitext.com/${english[slug]}`;
}
